export function translate(lang: Lang, key: DictKey, vars?: Record<string, string>): string {
  const raw = DICTIONARIES[lang]?.[key] ?? en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, name) => vars[name] ?? m)
}
